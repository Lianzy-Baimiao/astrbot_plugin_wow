def pick_quote(arg: str = "") -> dict:
    """取一条台词。arg 为空则全库随机；否则按 BOSS 名/别名检索。"""
    import random
    if arg:
        key = BOSS_ALIAS.get(arg)
        if key and key in QUOTE_DB:
            return random.choice(QUOTE_DB[key])
        for boss, lines in QUOTE_DB.items():
            for q in lines:
                if arg in q["boss"] or q["boss"] in arg:
                    return q
    keys = list(QUOTE_DB.keys())
    return random.choice(QUOTE_DB[random.choice(keys)])