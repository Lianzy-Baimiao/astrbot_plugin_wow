def pick_menu() -> str:
    """随机点菜，与原版 getMenu() 行为一致。

    4:00~9:59 从早餐池抽 0~2 道；其余时段抽 0~4 道，每道先五五开决定
    午餐池还是晚餐池。抽取有放回（同一道菜可能重复），0 道时返回吐槽语。
    """
    hour = datetime.datetime.now().hour
    picks: list[str] = []
    if 4 <= hour < 10:
        num = random.randrange(3)
        for _ in range(num):
            picks.append(BREAKFAST[random.randrange(len(BREAKFAST))])
    else:
        num = random.randrange(5)
        for _ in range(num):
            pool = LUNCH if random.randrange(2) == 0 else DINNER
            picks.append(pool[random.randrange(len(pool))])
    if num == 0:
        return "你不配吃饭，请喝西北风吧"
    return ", ".join(picks)
