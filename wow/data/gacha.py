def roll_quality() -> dict:
    import random
    total = sum(q["odd"] for q in QUALITIES)
    r = random.randint(0, total - 1)
    for q in QUALITIES:
        if r < q["odd"]:
            return q
        r -= q["odd"]
    return QUALITIES[0]


